import { spawn, type ChildProcessWithoutNullStreams } from 'node:child_process';
import { createHash } from 'node:crypto';
import { createReadStream } from 'node:fs';
import { createInterface } from 'node:readline';
import { EventEmitter } from 'node:events';
import type { ClientRequest } from './protocol/ClientRequest';
import type { ServerNotification } from './protocol/ServerNotification';
import type { ServerRequest } from './protocol/ServerRequest';
import type { RequestId } from './protocol/RequestId';
import type { CollaborationMode } from './protocol/CollaborationMode';
import { PIN } from './pin';
import { instanceArgs,type WorkspaceFilesPolicy } from './tools';
import {WORKSPACE_FILES_SERVER,fileArguments} from './workspace-files-contract';

export type Notification = ServerNotification;
export type IncomingRequest = ServerRequest;
type StableRequestParams = {[M in ClientRequest['method']]: Extract<ClientRequest, {method: M}>['params']};
// Public experimental fields generated by the same pinned binary. Do not widen
// arbitrary RPC dispatch or change the stable protocol's generated declarations.
type RequestParams = Omit<StableRequestParams,'turn/start'> & {
  'turn/start': StableRequestParams['turn/start'] & {collaborationMode?: CollaborationMode};
  'collaborationMode/list': Record<string,never>;
};
export class RpcRequestRejected extends Error {readonly requestRejected=true;}
export interface Transport {
  readonly workspaceFiles?: WorkspaceFilesPolicy | undefined;
  readonly processId?: number | undefined;
  request<M extends keyof RequestParams, R = unknown>(method: M, params: RequestParams[M]): Promise<R>;
  respond(id: RequestId, result: unknown): void;
  reject(id: RequestId, message: string): void;
  on(event: 'notification' | 'request' | 'disconnect', listener: (...args: any[]) => void): this;
  dispose(): Promise<void>;
}

/** One owned stdio subprocess. This deliberately does not attach to Desktop's server. */
export class Rpc extends EventEmitter implements Transport {
  get processId(): number | undefined { return this.child.pid; }
  private nextId = 0;
  private closed = false;
  private pending = new Map<RequestId, {resolve: (v: unknown) => void; reject: (e: Error) => void; timer: NodeJS.Timeout}>();
  private lines;
  constructor(private child: ChildProcessWithoutNullStreams, private timeoutMs = 60_000, private readonly allowModelDispatch = true,readonly workspaceFiles?:WorkspaceFilesPolicy) {
    super();
    this.lines = createInterface({input: child.stdout, crlfDelay: Infinity});
    this.lines.on('line', line => this.receive(line));
    // Drain stderr but never persist potentially sensitive diagnostics/auth material.
    child.stderr.on('data', () => {});
    child.on('error', e => this.fail(e));
    child.on('exit', code => this.fail(new Error(`App Server 已断开 (${code})`)));
    child.stdin.on('error', e => this.fail(e));
  }
  static async start(cwd: string, allowModelDispatch = true, nativeModes = false,workspaceScript?:string): Promise<Rpc> {
    const hash = createHash('sha256');
    try { for await (const chunk of createReadStream(PIN.path)) hash.update(chunk); }
    catch { throw new Error('无法读取 Codex 后端；请按本版本安装指南准备后端，或检查 CODEX_PROTOTYPE_BIN 指向的文件'); }
    if (hash.digest('hex') !== PIN.sha256) throw new Error('Codex 后端文件校验不匹配；请安装本版本支持的官方构建，不要仅按版本名称替换文件');
    // No auth files are read. The pinned process manages the existing Codex login.
    const policy=workspaceScript?{command:process.execPath,script:workspaceScript,root:cwd}:undefined;
    const rpc = new Rpc(spawn(PIN.path, instanceArgs(policy), {cwd, windowsHide: true, stdio: 'pipe'}),60_000,allowModelDispatch,policy);
    try {
      await rpc.request('initialize', {clientInfo: {name: 'codex_sidebar', title: 'Codex Sidebar', version: '0.1.78-dev.23'}, capabilities: {experimentalApi: nativeModes, requestAttestation: false}});
      rpc.write({method: 'initialized'});
      return rpc;
    } catch (e) { await rpc.dispose(); throw e; }
  }
  private write(value: unknown): void {
    if (this.closed) throw new Error('App Server 连接已关闭');
    this.child.stdin.write(JSON.stringify(value) + '\n');
  }
  request<M extends keyof RequestParams, R = unknown>(method: M, params: RequestParams[M]): Promise<R> {
    if(this.closed)return Promise.reject(new Error('App Server 连接已关闭'));
    if(method==='mcpServer/tool/call'){
      const call=params as RequestParams['mcpServer/tool/call'];
      try{if(!this.workspaceFiles||call.server!==WORKSPACE_FILES_SERVER||!call.threadId||call._meta!=null)throw Error();fileArguments(call.tool,call.arguments);}catch{return Promise.reject(new RpcRequestRejected('仅准入工作区文件只读调用'));}
    }
    if(!this.allowModelDispatch&&(method==='turn/start'||method==='turn/steer'||method==='thread/compact/start'))return Promise.reject(new RpcRequestRejected('当前连接未获发送授权；未向后端派发模型请求'));
    if(!this.allowModelDispatch&&method==='thread/revert')return Promise.reject(new RpcRequestRejected('仅连接检查不允许修改对话历史'));
    const id = ++this.nextId;
    return new Promise((resolve, reject) => {
      const appMetadataRead=['app/list','app/installed','app/read'].includes(method);
      const informationalRead = appMetadataRead||method === 'account/rateLimits/read'||method==='mcpServer/tool/call'&&this.workspaceFiles?.root!==undefined;
      const timer = setTimeout(() => {
        // This optional read has no delivery ambiguity. Expire only its entry;
        // ignore a late reply without interrupting chat or retrying the request.
        if(informationalRead){this.pending.delete(id);reject(new Error(appMetadataRead?'应用目录读取超时；聊天连接保留，可手动重试':method==='account/rateLimits/read'?'账户额度读取超时；聊天连接保留，可手动刷新':'文件读取超时；聊天连接保留，可手动重试'));return;}
        // A timed-out turn/start may have executed: disconnect instead of pretending idle.
        this.fail(new Error(`请求超时: ${method}`));
      }, informationalRead ? Math.min(this.timeoutMs,15_000) : this.timeoutMs);
      this.pending.set(id, {resolve: v => resolve(v as R), reject, timer});
      try { this.write({id, method, params}); }
      catch (e) { this.fail(e as Error); }
    });
  }
  respond(id: RequestId, result: unknown): void { this.write({id, result}); }
  reject(id: RequestId, message: string): void { this.write({id, error: {code: -32601, message}}); }
  private receive(line: string): void {
    if (this.closed) return;
    try {
      const msg = JSON.parse(line);
      if (!msg || typeof msg !== 'object') throw new Error('无效协议消息');
      if (typeof msg.method === 'string') {
        this.emit(msg.id === undefined ? 'notification' : 'request', msg);
      } else if (msg.id !== undefined && ('result' in msg || 'error' in msg)) {
        const pending = this.pending.get(msg.id);
        if (!pending) return;
        // A malformed failure is not proof that a write was rejected. Leave it
        // pending for fail() to reject as an unknown transport outcome.
        if('error' in msg&&('result' in msg||!msg.error||typeof msg.error!=='object'||!Number.isInteger(msg.error.code)||typeof msg.error.message!=='string'))throw new Error('无效协议错误回执');
        clearTimeout(pending.timer); this.pending.delete(msg.id);
        if ('error' in msg) pending.reject(new RpcRequestRejected(msg.error.message));
        else pending.resolve(msg.result);
      } else throw new Error('无效协议信封');
    } catch (e) { this.fail(e as Error); }
  }
  private fail(e: Error): void {
    if (this.closed) return;
    this.closed = true;
    for (const p of this.pending.values()) { clearTimeout(p.timer); p.reject(e); }
    this.pending.clear(); this.lines.close();
    // A failed observer must not prevent other owners from invalidating state,
    // or escape before the caller terminates this owned process. rawListeners
    // preserves EventEmitter's once wrappers and snapshot dispatch semantics.
    for(const listener of this.rawListeners('disconnect'))try{listener.call(this,e);}catch{/* Preserve the original failure for all remaining observers. */}
    if(this.child.exitCode===null&&this.child.signalCode==null)this.child.kill();
  }
  async dispose(): Promise<void> {
    this.fail(new Error('本任务的 App Server 已停止'));
    if (this.child.exitCode !== null || this.child.signalCode != null) return;
    await new Promise<void>(resolve=>{
      const exited=()=>{clearTimeout(timer);resolve();};
      const timer=setTimeout(()=>{this.child.off('exit',exited);resolve();},3000);
      this.child.once('exit',exited);
    });
  }
}
